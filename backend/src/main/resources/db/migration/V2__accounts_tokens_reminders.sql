-- One-time tokens: e-mail verification, password reset and refresh tokens (only SHA-256 hashes are stored).
CREATE TABLE user_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    type       VARCHAR(30)              NOT NULL,
    token_hash VARCHAR(64)              NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_user_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX idx_user_tokens_user_type ON user_tokens (user_id, type);
CREATE INDEX idx_user_tokens_expires ON user_tokens (expires_at);
